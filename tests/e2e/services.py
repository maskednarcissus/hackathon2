"""Service table for the full local stack.

Single source for ``tests/e2e/run_e2e.py --local`` and for generating
``infrastructure/docker/docker-compose.full.yml`` (``python tests/e2e/services.py --compose``).
"""

from __future__ import annotations

import sys
from dataclasses import dataclass, field
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]


@dataclass(frozen=True)
class Service:
    name: str
    kind: str  # "node" | "python"
    path: str
    port: int
    url_vars: tuple[str, ...]
    extra_env: dict[str, str] = field(default_factory=dict)
    shared_audio: bool = False


SERVICES: tuple[Service, ...] = (
    Service("identity", "node", "services/identity", 4001, ("IDENTITY_URL", "IDENTITY_SERVICE_URL")),
    Service(
        "organization", "node", "services/organization", 4002,
        ("ORGANIZATION_URL", "ORGANIZATION_SERVICE_URL"),
    ),
    Service(
        "academic-integration", "node", "services/academic-integration", 4003,
        ("ACADEMIC_INTEGRATION_URL", "ACADEMIC_INTEGRATION_SERVICE_URL"),
    ),
    Service("device-management", "node", "services/device-management", 4004, ("DEVICE_MANAGEMENT_URL",)),
    Service("calendar", "node", "services/calendar", 4005, ("CALENDAR_URL",)),
    Service("notifications", "node", "services/notifications", 4006, ("NOTIFICATIONS_URL",)),
    Service(
        "transcript-management", "node", "services/transcript-management", 4008,
        ("TRANSCRIPT_MANAGEMENT_URL", "TRANSCRIPT_MANAGEMENT_SERVICE_URL"),
    ),
    Service("academic-analytics", "node", "services/academic-analytics", 4009, ("ACADEMIC_ANALYTICS_URL",)),
    Service(
        "group-intelligence", "node", "services/group-intelligence", 4010,
        ("GROUP_INTELLIGENCE_URL",), {"WAREHOUSE": "postgres"},
    ),
    Service("audit", "node", "services/audit", 4011, ("AUDIT_URL", "AUDIT_SERVICE_URL")),
    Service(
        "audio-ingestion", "python", "services/audio-ingestion", 8001, ("AUDIO_INGESTION_URL",),
        {"AUDIO_LOCAL_STORAGE_DIR": "{data}/audio", "UPLOAD_STAGING_DIR": "{data}/staging"},
        shared_audio=True,
    ),
    Service(
        "audio-processing", "python", "services/audio-processing", 8002, ("AUDIO_PROCESSING_URL",),
        {"AUDIO_LOCAL_STORAGE_DIR": "{data}/audio", "PROCESSING_WORK_DIR": "{data}/work"},
        shared_audio=True,
    ),
    Service("transcription", "python", "services/transcription", 8003, ("TRANSCRIPTION_URL",)),
    Service(
        "speaker-diarization", "python", "services/speaker-diarization", 8004,
        ("SPEAKER_DIARIZATION_URL",),
        {"AUDIO_LOCAL_ROOT": "{data}/audio", "AUDIO_LOCAL_STORAGE_DIR": "{data}/audio"},
        shared_audio=True,
    ),
    Service(
        "ai-gateway", "python", "services/ai-gateway", 8005, ("AI_GATEWAY_URL",),
        {"AI_GATEWAY_PROMPTS_DIR": "{service_dir}/prompts"},
    ),
    Service(
        "lecture-intelligence", "python", "services/lecture-intelligence", 8006,
        ("LECTURE_INTELLIGENCE_URL",),
    ),
    Service("event-extraction", "python", "services/event-extraction", 8007, ("EVENT_EXTRACTION_URL",)),
)

BUS_PORT = 8090


def url_env(host_for: dict[str, str]) -> dict[str, str]:
    """Every service-URL variable (all aliases) given ``service name → base URL``."""
    env: dict[str, str] = {}
    for s in SERVICES:
        for var in s.url_vars:
            env[var] = host_for[s.name]
    env["IDENTITY_JWKS_URL"] = host_for["identity"] + "/.well-known/jwks.json"
    env["SYNC_TARGETS"] = ",".join(
        f"{n}={host_for[n]}" for n in ("identity", "calendar", "notifications", "academic-analytics")
    )
    env["DSR_HANDLER_URLS"] = ",".join(
        f"{n}={host_for[n]}"
        for n in ("transcript-management", "lecture-intelligence", "notifications", "calendar", "audit")
    )
    return env


def render_compose() -> str:
    hosts = {s.name: f"http://{s.name}:{s.port}" for s in SERVICES}
    out: list[str] = []
    w = out.append
    w("# Classroom Intelligence — full local stack (integration stage §7).")
    w("# GENERATED by `python tests/e2e/services.py --compose` — edit the service table there.")
    w("#")
    w("#   docker compose -f infrastructure/docker/docker-compose.full.yml up --build")
    w("#   python tests/e2e/run_e2e.py        # against the published localhost ports")
    w("#")
    w("# Fake STT/LLM providers; one Postgres database with every migration applied by `migrations`.")
    w("name: classroom-intelligence")
    w("")
    w("x-common-env: &common-env")
    w("  DATABASE_URL: postgresql://ci:ci_dev@postgres:5432/classroom_intelligence")
    w(f"  EVENT_BUS_URL: http://dev-event-bus:{BUS_PORT}")
    for k, v in url_env(hosts).items():
        w(f"  {k}: {v}")
    w("")
    w("x-service: &service")
    w("  env_file: [full-stack.env]")
    w("  restart: unless-stopped")
    w("  depends_on:")
    w("    migrations:")
    w("      condition: service_completed_successfully")
    w("    dev-event-bus:")
    w("      condition: service_started")
    w("")
    w("services:")
    w("  postgres:")
    w("    image: postgres:16-alpine")
    w("    environment:")
    w("      POSTGRES_USER: ci")
    w("      POSTGRES_PASSWORD: ci_dev")
    w("      POSTGRES_DB: classroom_intelligence")
    w("    ports: ['5432:5432']")
    w("    volumes: [postgres_data:/var/lib/postgresql/data]")
    w("    healthcheck:")
    w("      test: ['CMD-SHELL', 'pg_isready -U ci -d classroom_intelligence']")
    w("      interval: 3s")
    w("      timeout: 3s")
    w("      retries: 20")
    w("")
    w("  migrations:")
    w("    image: postgres:16-alpine")
    w("    depends_on:")
    w("      postgres:")
    w("        condition: service_healthy")
    w("    environment:")
    w("      PGHOST: postgres")
    w("      PGUSER: ci")
    w("      PGPASSWORD: ci_dev")
    w("      PGDATABASE: classroom_intelligence")
    w("    volumes:")
    w("      - ../../data/migrations:/migrations:ro")
    w("      - ./apply-migrations.sh:/apply-migrations.sh:ro")
    w("    entrypoint: ['sh', '/apply-migrations.sh', '/migrations']")
    w("")
    w("  dev-event-bus:")
    w("    build:")
    w("      context: ../..")
    w("      dockerfile: infrastructure/docker/Dockerfile.node")
    w("      args: { SERVICE_PATH: infrastructure/dev-event-bus }")
    w("    env_file: [full-stack.env]")
    w("    environment:")
    w("      <<: *common-env")
    w(f"      PORT: '{BUS_PORT}'")
    w("      SUBSCRIPTIONS_FILE: /events/subscriptions.yaml")
    w("      BUS_TIMEOUT_MS: '600000'")
    w(f"    ports: ['{BUS_PORT}:{BUS_PORT}']")
    for s in SERVICES:
        w("")
        w(f"  {s.name}:")
        w("    <<: *service")
        w("    build:")
        w("      context: ../..")
        w(f"      dockerfile: infrastructure/docker/Dockerfile.{s.kind}")
        w(f"      args: {{ SERVICE_PATH: {s.path} }}")
        w("    environment:")
        w("      <<: *common-env")
        w(f"      PORT: '{s.port}'")
        for k, v in s.extra_env.items():
            w(f"      {k}: {v.format(data='/data', service_dir='/app')}")
        w(f"    ports: ['{s.port}:{s.port}']")
        if s.shared_audio:
            w("    volumes: [audio_data:/data]")
    w("")
    w("volumes:")
    w("  postgres_data:")
    w("  audio_data:")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    if "--compose" in sys.argv:
        target = REPO / "infrastructure/docker/docker-compose.full.yml"
        target.write_text(render_compose(), encoding="utf-8")
        print(f"wrote {target}")
    else:
        for s in SERVICES:
            print(f"{s.name:24} {s.kind:7} {s.port}")
