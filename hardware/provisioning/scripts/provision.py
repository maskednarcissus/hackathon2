#!/usr/bin/env python3
"""Request a device provisioning token and write the device's config.toml.

Standard library only, so it runs on any admin workstation.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path


def request_token(
    base_url: str, admin_token: str | None, serial: str, institution_id: str, hours: int
) -> dict[str, object]:
    body = json.dumps(
        {"serialNumber": serial, "institutionId": institution_id, "expiresInHours": hours}
    ).encode()
    req = urllib.request.Request(
        base_url.rstrip("/") + "/v1/provisioning-tokens",
        data=body,
        method="POST",
        headers={"Content-Type": "application/json", "Accept": "application/json"},
    )
    if admin_token:
        req.add_header("Authorization", f"Bearer {admin_token}")
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:  # noqa: S310 (admin-supplied URL)
            data: dict[str, object] = json.load(resp)
            return data
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode(errors="replace")
        raise SystemExit(f"provisioning token request failed: HTTP {exc.code}: {detail}") from exc


def toml_str(value: str) -> str:
    return json.dumps(value)  # JSON string escaping is valid TOML basic-string escaping


def render_config(args: argparse.Namespace) -> str:
    return "\n".join(
        [
            "# Generated by hardware/provisioning/scripts/provision.py",
            "[agent]",
            f"device_management_url = {toml_str(args.device_management_url)}",
            f"ingestion_url = {toml_str(args.ingestion_url)}",
            f"serial_number = {toml_str(args.serial)}",
            f"model = {toml_str(args.model)}",
            'data_dir = "/var/lib/ci-agent"',
            "",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--device-management-url", required=True)
    p.add_argument("--ingestion-url", required=True)
    p.add_argument("--admin-token", default=os.environ.get("CI_ADMIN_TOKEN"))
    p.add_argument("--serial", required=True)
    p.add_argument("--institution-id", required=True)
    p.add_argument("--model", default="ci-capture-a1")
    p.add_argument("--expires-in-hours", type=int, default=72)
    p.add_argument("--out", type=Path, required=True, help="path of the config.toml to write")
    args = p.parse_args(argv)

    result = request_token(
        args.device_management_url,
        args.admin_token,
        args.serial,
        args.institution_id,
        args.expires_in_hours,
    )
    token = result.get("token") or result.get("provisioningToken")
    if not isinstance(token, str):
        raise SystemExit(f"unexpected response (no token): {result}")
    args.out.write_text(render_config(args), encoding="utf-8")
    print(f"config written to {args.out}", file=sys.stderr)
    print(f"provisioning token (single use, expires {result.get('expiresAt', '?')}):")
    print(token)
    print(f"on the device: ci-agent register --token {token}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
