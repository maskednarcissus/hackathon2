"""Personalised revision materials and spaced repetition (deliverable 6.2).

Plans are built only from (a) lecture structures of the student's own class sections and (b) the
student's *own* signals — their assistant questions, their review history and an explicit focus
list. No other student's data is ever read. Flashcards and quiz questions are generated by the
AI gateway (prompt ``revision-materials``) and validated with the same grounding rules as lecture
structures; summaries and concept reviews are taken from the already-validated structures.
Spaced repetition follows SM-2.
"""

